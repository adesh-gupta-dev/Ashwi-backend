import 'dotenv/config';
import { query } from '../config/db.js';
import logger from '../utils/logger.js';
import { PROFESSIONS } from '../config/professions.js';

const initializeDatabase = async () => {
  try {
    await query(`
      CREATE TABLE IF NOT EXISTS professions (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        key_name VARCHAR(60) NOT NULL UNIQUE,
        label VARCHAR(120) NOT NULL,
        icon VARCHAR(80) NOT NULL DEFAULT 'smart_toy',
        prompt TEXT NOT NULL,
        is_active BOOLEAN NOT NULL DEFAULT TRUE,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
        updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      );
    `);

    await query(`
      CREATE TABLE IF NOT EXISTS users (
        id UUID PRIMARY KEY,
        name VARCHAR(120) NOT NULL,
        email VARCHAR(255) NOT NULL UNIQUE,
        password_hash VARCHAR(255),
        role VARCHAR(50) NOT NULL DEFAULT 'user',
        is_active BOOLEAN NOT NULL DEFAULT TRUE,
        is_verified BOOLEAN NOT NULL DEFAULT FALSE,
        is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
        verification_token VARCHAR(255),
        reset_token VARCHAR(255),
        reset_token_expires TIMESTAMPTZ NULL,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
        updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      );
    `);

    await query('ALTER TABLE users ALTER COLUMN password_hash DROP NOT NULL');
    await query(`CREATE TABLE IF NOT EXISTS oauth_identities (
      provider VARCHAR(20) NOT NULL CHECK (provider IN ('google','github')),
      subject VARCHAR(255) NOT NULL,
      user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      PRIMARY KEY (provider, subject), UNIQUE (user_id, provider)
    )`);
    await query(`CREATE TABLE IF NOT EXISTS oauth_attempts (
      state_hash VARCHAR(64) PRIMARY KEY, provider VARCHAR(20) NOT NULL,
      provider_verifier TEXT NOT NULL, nonce TEXT NOT NULL,
      redirect_uri TEXT NOT NULL, client_challenge VARCHAR(64) NOT NULL,
      link_user_id UUID REFERENCES users(id) ON DELETE CASCADE, expires_at TIMESTAMPTZ NOT NULL
    )`);
    await query(`CREATE TABLE IF NOT EXISTS oauth_handoffs (
      ticket_hash VARCHAR(64) PRIMARY KEY, client_challenge VARCHAR(64) NOT NULL,
      link_user_id UUID REFERENCES users(id) ON DELETE CASCADE,
      identity JSONB NOT NULL, expires_at TIMESTAMPTZ NOT NULL
    )`);
    await query('CREATE INDEX IF NOT EXISTS idx_oauth_attempt_expiry ON oauth_attempts (expires_at)');
    await query('CREATE INDEX IF NOT EXISTS idx_oauth_handoff_expiry ON oauth_handoffs (expires_at)');

    await query(`
      CREATE TABLE IF NOT EXISTS chats (
        id UUID PRIMARY KEY,
        user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        profession_id INTEGER NOT NULL REFERENCES professions(id) ON DELETE RESTRICT,
        session_id VARCHAR(255) NOT NULL,
        persona_role VARCHAR(50) NOT NULL,
        user_message TEXT NOT NULL,
        ai_response TEXT NOT NULL,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      );
    `);

    await query(`
      CREATE TABLE IF NOT EXISTS logs (
        id UUID PRIMARY KEY,
        user_id UUID NULL REFERENCES users(id) ON DELETE SET NULL,
        action VARCHAR(255) NOT NULL,
        details JSONB,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      );
    `);

    await query(`
      CREATE TABLE IF NOT EXISTS subscription_plans (
        id UUID PRIMARY KEY,
        name VARCHAR(120) NOT NULL UNIQUE,
        description TEXT,
        price NUMERIC(10,2) NOT NULL DEFAULT 0.00,
        billing_cycle VARCHAR(30) NOT NULL DEFAULT 'monthly',
        duration_days INTEGER NOT NULL DEFAULT 30,
        features JSONB,
        is_active BOOLEAN NOT NULL DEFAULT TRUE,
        is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
        updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      );
    `);

    await query(`
      CREATE TABLE IF NOT EXISTS subscriptions (
        id UUID PRIMARY KEY,
        user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        plan_id UUID NOT NULL REFERENCES subscription_plans(id) ON DELETE RESTRICT,
        status VARCHAR(20) NOT NULL DEFAULT 'active',
        start_date TIMESTAMPTZ NOT NULL,
        end_date TIMESTAMPTZ NULL,
        renewal_date TIMESTAMPTZ NULL,
        auto_renew BOOLEAN NOT NULL DEFAULT FALSE,
        notes TEXT,
        plan_name VARCHAR(120) NOT NULL,
        plan_price NUMERIC(10,2) NOT NULL DEFAULT 0.00,
        plan_duration_days INTEGER NOT NULL DEFAULT 30,
        billing_cycle VARCHAR(30) NOT NULL DEFAULT 'monthly',
        is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
        updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      );
    `);

    await query('CREATE INDEX IF NOT EXISTS idx_chats_user_id ON chats (user_id)');
    await query('CREATE INDEX IF NOT EXISTS idx_chats_profession_id ON chats (profession_id)');
    await query('CREATE INDEX IF NOT EXISTS idx_chats_session_id ON chats (session_id)');
    await query('CREATE INDEX IF NOT EXISTS idx_logs_user_id ON logs (user_id)');
    await query('CREATE INDEX IF NOT EXISTS idx_subscription_plans_active ON subscription_plans (is_active, is_deleted)');
    await query('CREATE INDEX IF NOT EXISTS idx_subscriptions_user_id ON subscriptions (user_id)');
    await query('CREATE INDEX IF NOT EXISTS idx_subscriptions_plan_id ON subscriptions (plan_id)');
    await query('CREATE INDEX IF NOT EXISTS idx_subscriptions_status ON subscriptions (status)');
    await query('CREATE INDEX IF NOT EXISTS idx_subscriptions_created_at ON subscriptions (created_at)');

    await query(`
      CREATE OR REPLACE FUNCTION set_updated_at()
      RETURNS trigger AS $$
      BEGIN
        NEW.updated_at = NOW();
        RETURN NEW;
      END;
      $$ LANGUAGE plpgsql;
    `);

    await query('DROP TRIGGER IF EXISTS trg_professions_updated_at ON professions');
    await query(`
      CREATE TRIGGER trg_professions_updated_at
      BEFORE UPDATE ON professions
      FOR EACH ROW
      EXECUTE FUNCTION set_updated_at();
    `);

    await query('DROP TRIGGER IF EXISTS trg_users_updated_at ON users');
    await query(`
      CREATE TRIGGER trg_users_updated_at
      BEFORE UPDATE ON users
      FOR EACH ROW
      EXECUTE FUNCTION set_updated_at();
    `);

    await query('DROP TRIGGER IF EXISTS trg_subscription_plans_updated_at ON subscription_plans');
    await query(`
      CREATE TRIGGER trg_subscription_plans_updated_at
      BEFORE UPDATE ON subscription_plans
      FOR EACH ROW
      EXECUTE FUNCTION set_updated_at();
    `);

    await query('DROP TRIGGER IF EXISTS trg_subscriptions_updated_at ON subscriptions');
    await query(`
      CREATE TRIGGER trg_subscriptions_updated_at
      BEFORE UPDATE ON subscriptions
      FOR EACH ROW
      EXECUTE FUNCTION set_updated_at();
    `);

    for (const profession of Object.values(PROFESSIONS)) {
      await query(
        `
        INSERT INTO professions (key_name, label, icon, prompt, is_active)
        VALUES (?, ?, ?, ?, TRUE)
        ON CONFLICT (key_name) DO UPDATE SET
          label = EXCLUDED.label,
          icon = EXCLUDED.icon,
          prompt = EXCLUDED.prompt,
          is_active = TRUE
        `,
        [profession.keyName, profession.label, profession.icon, profession.prompt]
      );
    }

    const assistant = await query('SELECT id FROM professions WHERE key_name = ? LIMIT 1', ['assistant']);
    const assistantId = assistant?.[0]?.id ?? null;

    if (assistantId) {
      await query(
        `
        UPDATE chats c
        SET profession_id = p.id
        FROM professions p
        WHERE c.profession_id IS NULL
          AND p.key_name = c.persona_role
        `,
        []
      );

      await query(
        'UPDATE chats SET profession_id = ? WHERE profession_id IS NULL',
        [assistantId]
      );
    }

    logger.info('Database initialized successfully for PostgreSQL');
  } catch (error) {
    logger.error('Error initializing database:', error);
    throw error;
  }
};

export { initializeDatabase };
